using System.Collections.Generic;
using System.Linq;
using UnityEngine;
using UnityEngine.EventSystems;
using UnityEngine.UI;
using IDS.Core;

namespace IDS.XR
{
    /// <summary>
    /// Makes the world-space menus pressable. Two independent ways in, both
    /// always active:
    ///
    ///     CONTROLLER RAY    point, pull the trigger
    ///     GAZE AND DWELL    look at a button for a moment with no controller
    ///
    /// Both routes exist because the single most common failure on this project
    /// was a driver in the headset looking at a Start button with no way to press
    /// it — once because the canvas had no camera assigned to its raycaster, once
    /// because no controller was paired at all. Gaze-and-dwell needs neither a
    /// controller nor any configuration, so the menu can always be operated.
    ///
    /// WHY NOT XRI's ray interactor: XRRayInteractor and XRUIInputModule read
    /// input through serialized InputActionProperty fields. A scene generated by
    /// script cannot verify that wiring, and when it is wrong the interactor does
    /// nothing and reports nothing. This component's only dependency is a
    /// GraphicRaycaster on the canvas, which the scene builder guarantees, and it
    /// logs what it hit.
    ///
    /// Every canvas it raycasts against must have its worldCamera set — a
    /// GraphicRaycaster with no camera cannot project a world ray onto the canvas
    /// and silently misses every button. The scene builder sets it; this component
    /// checks and repairs it at startup rather than trusting it.
    /// </summary>
    public class VRUIPointer : MonoBehaviour
    {
        [Header("Sources")]
        [SerializeField] private Camera headCamera;
        [SerializeField] private XRControllerAnchor leftAnchor;
        [SerializeField] private XRControllerAnchor rightAnchor;

        [Header("Ray")]
        [SerializeField] private float maxDistance = 8f;
        [SerializeField] private float triggerPressThreshold = 0.6f;
        [SerializeField] private float triggerReleaseThreshold = 0.35f;

        [Header("Laser line")]
        [SerializeField] private LineRenderer leftLine;
        [SerializeField] private LineRenderer rightLine;
        [SerializeField] private Color lineIdleColour = new Color(0.45f, 0.65f, 1f, 0.5f);
        [SerializeField] private Color lineHitColour = new Color(0.4f, 1f, 0.75f, 0.95f);

        [Header("Gaze fallback")]
        [Tooltip("Seconds of continuous gaze that counts as a press.")]
        [SerializeField] private float dwellSeconds = 1.3f;

        [Tooltip("Reticle shown at the gaze point. Its Image is driven as a " +
                 "radial fill to show dwell progress.")]
        [SerializeField] private Image dwellReticle;
        [SerializeField] private GameObject reticleRoot;

        [Tooltip("Use gaze even when a controller is present. Off by default: " +
                 "with a controller in hand, a dwell press fires buttons the " +
                 "driver only glanced at.")]
        [SerializeField] private bool gazeAlwaysActive;

        private readonly List<RaycastResult> _hits = new();
        private readonly bool[] _triggerDown = new bool[2];

        private List<Canvas> _canvases;
        private bool _canvasesStale = true;

        private GameObject _gazeTarget;
        private GameObject _hovered;
        private float _gazeStarted;
        private bool _loggedNoEventSystem;

        private void Awake() => ServiceRegistry.Register(this);

        private void Start()
        {
            if (headCamera == null) headCamera = Camera.main;
            RepairCanvasCameras();
        }

        private void Update()
        {
            GameObject leftTarget = TickController(Hand.Left, 0, leftAnchor, leftLine);
            GameObject rightTarget = TickController(Hand.Right, 1, rightAnchor, rightLine);

            GameObject controllerTarget = rightTarget ?? leftTarget;

            bool useGaze = gazeAlwaysActive || !XRControls.AnyAvailable;
            GameObject gazeTarget = TickGaze(useGaze && controllerTarget == null);

            SetHover(controllerTarget ?? gazeTarget);
        }

        // ---- controller ray --------------------------------------------------

        /// <summary>Returns the button this hand is pointing at, or null.</summary>
        private GameObject TickController(Hand hand, int slot, XRControllerAnchor anchor,
                                          LineRenderer line)
        {
            if (anchor == null || !anchor.IsTracked)
            {
                if (line != null) line.enabled = false;
                _triggerDown[slot] = false;
                return null;
            }

            Transform origin = anchor.transform;
            GameObject target = RaycastUI(origin.position, origin.forward, out Vector3 hitPoint);

            if (line != null)
            {
                line.enabled = true;
                line.positionCount = 2;
                line.SetPosition(0, origin.position);
                line.SetPosition(1, target != null
                    ? hitPoint
                    : origin.position + origin.forward * maxDistance);
                Color c = target != null ? lineHitColour : lineIdleColour;
                line.startColor = c;
                line.endColor = c;
            }

            // Analogue threshold with hysteresis, rather than a "triggerPressed"
            // button that not every OpenXR controller layout exposes.
            float t = XRControls.Trigger(hand);

            if (!_triggerDown[slot] && t >= triggerPressThreshold)
            {
                _triggerDown[slot] = true;
                if (target != null) Press(target, $"{hand} controller");
            }
            else if (_triggerDown[slot] && t <= triggerReleaseThreshold)
            {
                _triggerDown[slot] = false;
            }

            return target;
        }

        // ---- gaze and dwell --------------------------------------------------

        /// <summary>Returns the button being gazed at, or null.</summary>
        private GameObject TickGaze(bool active)
        {
            if (!active || headCamera == null)
            {
                ClearGaze();
                return null;
            }

            Transform head = headCamera.transform;
            GameObject target = RaycastUI(head.position, head.forward, out Vector3 hitPoint);

            if (target == null || target != _gazeTarget)
            {
                _gazeTarget = target;
                _gazeStarted = Time.time;
            }

            if (reticleRoot != null)
            {
                bool show = target != null;
                if (reticleRoot.activeSelf != show) reticleRoot.SetActive(show);
                if (show) reticleRoot.transform.position = hitPoint - head.forward * 0.01f;
                if (show) reticleRoot.transform.rotation = Quaternion.LookRotation(head.forward);
            }

            if (target == null) return null;

            float held = Time.time - _gazeStarted;
            if (dwellReticle != null)
                dwellReticle.fillAmount = Mathf.Clamp01(held / dwellSeconds);

            if (held < dwellSeconds) return target;

            Press(target, "gaze dwell");
            ClearGaze();
            return null;
        }

        private void ClearGaze()
        {
            _gazeTarget = null;
            _gazeStarted = Time.time;
            if (dwellReticle != null) dwellReticle.fillAmount = 0f;
            if (reticleRoot != null && reticleRoot.activeSelf) reticleRoot.SetActive(false);
        }

        // ---- shared raycast and press ----------------------------------------

        /// <summary>
        /// Raycasts the UI along a world ray and returns the nearest pressable
        /// Button, or null.
        ///
        /// Two steps, and the first is what makes it exact. The ray is intersected
        /// with each active world-space canvas's own plane to find the world point
        /// the ray actually lands on. Only then is that point projected into screen
        /// space for the stock GraphicRaycaster to resolve.
        ///
        /// Projecting the ray's far point directly would be wrong for a controller
        /// ray: the head camera's projection of a point 8 m along the controller's
        /// forward axis corresponds to a ray from the HEAD through that point, not
        /// the controller's ray, and the two diverge by the controller's offset
        /// from the eyes. Because the intersection point lies on the canvas plane,
        /// projecting it is exact — the camera and the canvas agree about where it
        /// is.
        ///
        /// GraphicRaycaster still does the hierarchy work, so masks, sorting and
        /// every Selectable behave exactly as they do on a flat canvas.
        /// </summary>
        private GameObject RaycastUI(Vector3 origin, Vector3 direction, out Vector3 hitPoint)
        {
            hitPoint = origin + direction * maxDistance;

            if (EventSystem.current == null)
            {
                if (!_loggedNoEventSystem)
                {
                    _loggedNoEventSystem = true;
                    Debug.LogError("[VRUIPointer] no EventSystem in the scene, so no " +
                                   "menu can ever be pressed. Rebuild the scene with " +
                                   "Tools → Intelli-Driving → Build Main Scene.");
                }
                return null;
            }

            if (headCamera == null) return null;

            CollectCanvasHits(origin, direction);

            // Near to far. A ray that crosses a panel with no button at that point
            // must carry on to the one behind it, rather than reporting nothing:
            // in this cabin the alert banner sits between the driver and the menu,
            // and "nearest canvas only" meant every ray aimed at the upper half of
            // the menu hit the banner and found no button.
            _canvasHits.Sort((a, b) => a.Distance.CompareTo(b.Distance));

            foreach (CanvasHit candidate in _canvasHits)
            {
                Vector3 screen = headCamera.WorldToScreenPoint(candidate.Point);
                if (screen.z <= 0f) continue;   // behind the head

                var data = new PointerEventData(EventSystem.current) { position = screen };

                _hits.Clear();
                EventSystem.current.RaycastAll(data, _hits);

                foreach (RaycastResult hit in _hits)
                {
                    if (hit.gameObject == null) continue;

                    Button button = hit.gameObject.GetComponentInParent<Button>();
                    if (button == null || !button.IsInteractable()) continue;

                    // Only a button on the canvas this candidate point lies on.
                    if (button.GetComponentInParent<Canvas>() != candidate.Canvas) continue;

                    hitPoint = candidate.Point;
                    return button.gameObject;
                }
            }

            return null;
        }

        private struct CanvasHit
        {
            public Canvas Canvas;
            public Vector3 Point;
            public float Distance;
        }

        private readonly List<CanvasHit> _canvasHits = new();

        /// <summary>
        /// Every active, interactive world-space canvas the ray crosses inside the
        /// panel's own rectangle. Canvases are planes, so this is one dot product
        /// each.
        ///
        /// Canvases without a GraphicRaycaster are skipped: that is the marker for
        /// "decorative" in this scene — the HUD, the alert banner, the vignette and
        /// the gaze reticle are all built without one precisely so they cannot
        /// intercept a ray.
        /// </summary>
        private void CollectCanvasHits(Vector3 origin, Vector3 direction)
        {
            _canvasHits.Clear();

            if (_canvases == null || _canvasesStale) CacheCanvases();

            for (int i = 0; i < _canvases.Count; i++)
            {
                Canvas canvas = _canvases[i];
                if (canvas == null) { _canvasesStale = true; continue; }
                if (!canvas.isActiveAndEnabled) continue;

                Transform t = canvas.transform;
                Vector3 normal = t.forward;

                float denominator = Vector3.Dot(direction, normal);
                if (Mathf.Abs(denominator) < 1e-5f) continue;   // ray parallel to the panel

                float distance = Vector3.Dot(t.position - origin, normal) / denominator;
                if (distance <= 0.02f || distance > maxDistance) continue;

                Vector3 point = origin + direction * distance;

                if (t is RectTransform rect)
                {
                    Vector3 local = rect.InverseTransformPoint(point);
                    if (!rect.rect.Contains(new Vector2(local.x, local.y))) continue;
                }

                _canvasHits.Add(new CanvasHit
                {
                    Canvas = canvas,
                    Point = point,
                    Distance = distance
                });
            }
        }

        private void CacheCanvases()
        {
            _canvases = new List<Canvas>();
            _canvasesStale = false;

            Canvas[] all = FindObjectsByType<Canvas>(FindObjectsInactive.Include);

            var skipped = new List<string>();

            foreach (Canvas c in all)
            {
                if (c.renderMode != RenderMode.WorldSpace) continue;

                if (c.GetComponent<GraphicRaycaster>() == null)
                {
                    skipped.Add(c.name);
                    continue;
                }

                _canvases.Add(c);
            }

            Debug.Log($"[VRUIPointer] {_canvases.Count} interactive world-space " +
                      $"canvas(es): {string.Join(", ", _canvases.Select(c => c.name))}" +
                      (skipped.Count > 0
                          ? $"; ignoring {string.Join(", ", skipped)} (no raycaster)"
                          : ""));
        }

        private void Press(GameObject target, string via)
        {
            Button button = target.GetComponent<Button>();
            if (button == null || !button.IsInteractable()) return;

            Debug.Log($"[VRUIPointer] pressed '{PathOf(target.transform)}' via {via}");
            button.onClick.Invoke();
        }

        /// <summary>
        /// Drives Selectable highlight states by hand.
        ///
        /// Normally the EventSystem's input module sends pointerEnter/pointerExit.
        /// This scene has an EventSystem but deliberately no input module: the
        /// Input System's UI module needs a configured action asset to do anything,
        /// and the legacy module logs an error in a project with Active Input
        /// Handling set to Both. Sending the two events directly is four lines and
        /// has no configuration to get wrong.
        ///
        /// Without this a button gives no visual response until it is pressed,
        /// which testers reliably read as "the button is broken".
        /// </summary>
        private void SetHover(GameObject target)
        {
            if (target == _hovered) return;

            var data = new PointerEventData(EventSystem.current);

            if (_hovered != null)
                ExecuteEvents.Execute(_hovered, data, ExecuteEvents.pointerExitHandler);

            _hovered = target;

            if (_hovered != null)
                ExecuteEvents.Execute(_hovered, data, ExecuteEvents.pointerEnterHandler);
        }

        private static string PathOf(Transform t)
        {
            string path = t.name;
            while (t.parent != null)
            {
                t = t.parent;
                path = t.name + "/" + path;
            }
            return path;
        }

        // ---- canvas repair ---------------------------------------------------

        /// <summary>
        /// A world-space Canvas whose GraphicRaycaster has no camera cannot be hit
        /// by anything. This was the cause of "none of the panels have buttons":
        /// the buttons existed, the raycaster had nothing to project with. Checked
        /// and repaired here rather than assumed.
        ///
        /// A canvas with buttons but no raycaster is also repaired, because that
        /// is unambiguously a mistake. A canvas with NO buttons and no raycaster
        /// is left exactly as it is — that combination is how this scene marks a
        /// canvas as decorative, and adding a raycaster would turn the HUD into
        /// something that blocks the menu behind it.
        /// </summary>
        private void RepairCanvasCameras()
        {
            var canvases = FindObjectsByType<Canvas>(FindObjectsInactive.Include);
            int cameraFixes = 0, raycasterFixes = 0;

            foreach (Canvas canvas in canvases)
            {
                if (canvas.renderMode != RenderMode.WorldSpace) continue;

                if (canvas.worldCamera == null)
                {
                    canvas.worldCamera = headCamera;
                    cameraFixes++;
                }

                if (canvas.GetComponent<GraphicRaycaster>() != null) continue;

                bool hasButtons = canvas.GetComponentsInChildren<Button>(true).Length > 0;
                if (!hasButtons) continue;

                canvas.gameObject.AddComponent<GraphicRaycaster>();
                raycasterFixes++;
                Debug.LogWarning($"[VRUIPointer] '{canvas.name}' has buttons but no " +
                                 "GraphicRaycaster — added one. The scene builder " +
                                 "should have done this; check it.");
            }

            if (cameraFixes > 0)
                Debug.LogWarning($"[VRUIPointer] assigned the head camera to " +
                                 $"{cameraFixes} world-space canvas(es) that had none. " +
                                 "The scene builder should have done this — check it.");

            if (cameraFixes > 0 || raycasterFixes > 0) _canvasesStale = true;
        }

        public void Configure(Camera cam, XRControllerAnchor left, XRControllerAnchor right,
                              LineRenderer lineL, LineRenderer lineR,
                              GameObject reticle, Image reticleFill)
        {
            headCamera = cam;
            leftAnchor = left;
            rightAnchor = right;
            leftLine = lineL;
            rightLine = lineR;
            reticleRoot = reticle;
            dwellReticle = reticleFill;
        }
    }
}
